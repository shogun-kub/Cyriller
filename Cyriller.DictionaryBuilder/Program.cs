using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using Cyriller.Model.Json;
using Cyriller.Rule;

namespace Cyriller.DictionaryBuilder
{
    /// <summary>
    /// Генерирует <c>nouns.txt</c> и <c>adjectives.txt</c> из <c>nouns.json</c> и <c>adjectives.json</c>.
    /// Заменяет T4-шаблоны, которые требовали Visual Studio и .NET Framework.
    /// </summary>
    /// <remarks>
    /// Использование:
    /// <code>
    /// dotnet run --project Cyriller.DictionaryBuilder -- nouns &lt;nouns.json&gt; &lt;nouns.txt&gt;
    /// dotnet run --project Cyriller.DictionaryBuilder -- adjectives &lt;adjectives.json&gt; &lt;adjectives.txt&gt;
    /// </code>
    /// </remarks>
    public static class Program
    {
        private static readonly JsonSerializerOptions JsonOptions = new JsonSerializerOptions
        {
            PropertyNameCaseInsensitive = true,
            Converters = { new JsonStringEnumConverter() }
        };

        public static int Main(string[] args)
        {
            if (args.Length != 3 || (args[0] != "nouns" && args[0] != "adjectives"))
            {
                Console.WriteLine("Usage: Cyriller.DictionaryBuilder [nouns|adjectives] [source.json] [destination.txt]");
                return 1;
            }

            string kind = args[0];
            string source = args[1];
            string destination = args[2];

            if (!File.Exists(source))
            {
                Console.Error.WriteLine($"Source file not found: {source}");
                return 2;
            }

            return kind == "nouns"
                ? Build(source, destination, JsonSerializer.Deserialize<NounJson[]>(File.ReadAllText(source), JsonOptions), "nouns")
                : Build(source, destination, JsonSerializer.Deserialize<AdjectiveJson[]>(File.ReadAllText(source), JsonOptions), "adjectives");
        }

        private static int Build(string source, string destination, NounJson[] nouns, string kind)
        {
            if (nouns == null)
            {
                return 3;
            }

            List<string> rules = new List<string>();
            List<string> lines = new List<string>();

            foreach (NounJson noun in nouns)
            {
                int ruleIndex = GetRuleIndex(rules, new NounRule(noun).Value);

                lines.Add(noun.ToDictionaryString(ruleIndex));
            }

            WriteDictionary(destination, kind, rules, lines);

            return 0;
        }

        private static int Build(string source, string destination, AdjectiveJson[] adjectives, string kind)
        {
            if (adjectives == null)
            {
                return 3;
            }

            List<string> rules = new List<string>();
            List<string> lines = new List<string>();

            foreach (AdjectiveJson adjective in adjectives)
            {
                int ruleIndex = GetRuleIndex(rules, new AdjectiveRule(adjective).Value);

                lines.Add(adjective.ToDictionaryString(ruleIndex));
            }

            WriteDictionary(destination, kind, rules, lines);

            return 0;
        }

        private static int GetRuleIndex(List<string> rules, string rule)
        {
            int index = rules.IndexOf(rule);

            if (index < 0)
            {
                index = rules.Count;
                rules.Add(rule);
            }

            return index;
        }

        private static void WriteDictionary(string destination, string kind, List<string> rules, List<string> lines)
        {
            StringBuilder builder = new StringBuilder();

            builder.AppendLine($"// This file is autogenerated by Cyriller.DictionaryBuilder from {kind}.json.");
            builder.AppendLine("// DO NOT MODIFY IT!");
            builder.AppendLine($"// Use {kind}.json file instead.");
            builder.AppendLine();
            builder.AppendLine("// -- Start of the Rules block -- //");

            foreach (string rule in rules)
            {
                builder.AppendLine(rule);
            }

            builder.AppendLine("// -- End of the Rules block -- //");
            builder.AppendLine();

            foreach (string line in lines)
            {
                builder.AppendLine(line);
            }

            File.WriteAllText(destination, builder.ToString(), new UTF8Encoding(false));

            Console.WriteLine($"Wrote {lines.Count} entries and {rules.Count} rules to {destination}.");
        }
    }
}
